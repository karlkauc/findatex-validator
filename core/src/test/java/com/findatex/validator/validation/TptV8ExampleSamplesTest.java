package com.findatex.validator.validation;

import com.findatex.validator.domain.TptFile;
import com.findatex.validator.ingest.TptFileLoader;
import com.findatex.validator.report.QualityReport;
import com.findatex.validator.report.QualityScorer;
import com.findatex.validator.report.ScoreCategory;
import com.findatex.validator.spec.SpecCatalog;
import com.findatex.validator.template.api.ProfileKey;
import com.findatex.validator.template.tpt.TptProfiles;
import com.findatex.validator.template.tpt.TptRuleSet;
import com.findatex.validator.template.tpt.TptTemplate;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIf;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Smoke-tests the TPT V8 fixtures under {@code samples/tpt/v8/} (generated by
 * {@code tools/build_tpt_v8_samples.py}). {@code 00_showcase.xlsx} is the V8 demo file; the
 * numbered fixtures pin the behaviour that differs from V7 after
 * the final V8 spec (8 October 2026): N/A fields, issuer identifier type codes, single-purpose
 * LEI columns 115/119/140, the e1/e2/e3 securitisation codes, the new fields 150/151 and the
 * V8 floating-rate requirements.
 */
@EnabledIf("samplesPresent")
class TptV8ExampleSamplesTest {

    private static final TptTemplate TPT = new TptTemplate();
    private static final SpecCatalog CATALOG = TPT.specLoaderFor(TptTemplate.V8_0).load();
    private static final Set<ProfileKey> ALL = Set.of(
            TptProfiles.SOLVENCY_II, TptProfiles.IORP_EIOPA_ECB, TptProfiles.NW_675, TptProfiles.SST);

    static boolean samplesPresent() {
        return Files.isDirectory(samplesDir());
    }

    private static Path samplesDir() {
        Path cwd = Paths.get("").toAbsolutePath();
        Path direct = cwd.resolve("samples").resolve("tpt").resolve("v8");
        if (Files.isDirectory(direct)) return direct;
        Path parent = cwd.getParent();
        if (parent != null) {
            Path up = parent.resolve("samples").resolve("tpt").resolve("v8");
            if (Files.isDirectory(up)) return up;
        }
        return direct;
    }

    /**
     * The V8 demo behind "Try an example" (TPT V8.0 selected). Same two silent failure modes
     * as the V7 showcase — regenerated clean or regenerated broken — plus a V8-specific one:
     * a V7 leftover (wrong version string, N/A fields still filled, the XF-09 custodian pair)
     * would make the demo show migration noise instead of the curated defects.
     */
    @Test
    void showcaseIsARealisticImperfectV8Delivery() throws Exception {
        QualityReport r = run("00_showcase.xlsx");
        assertThat(r.file().rows()).as("showcase row count").hasSizeGreaterThanOrEqualTo(55);
        assertThat(r.file().unmappedHeaders()).as("every header maps to a V8 field").isEmpty();
        assertThat(r.perFundScores()).as("three funds, so per-fund scoring is exercised")
                .hasSize(3);

        assertThat(r.findings().stream().map(Finding::ruleId).map(id -> id.split("/")[0]).distinct())
                .as("distinct rule families on show")
                .hasSizeGreaterThanOrEqualTo(8);
        for (String expected : List.of(
                "FORMAT/21", "FORMAT/52", "FORMAT/15", "FORMAT/40", "FORMAT/150",
                "XF-04/POSITION_WEIGHT_SUM", "XF-05/CASH_PERCENTAGE",
                "XF-08/COUPON_FREQUENCY", "XF-10/INTEREST_RATE_TYPE",
                "XF-11/MATURITY_AFTER_REPORTING", "XF-14/UNDERLYING_CIC",
                "NOT_APPLICABLE/54")) {
            assertThat(r.findings()).extracting(Finding::ruleId)
                    .as("showcase must still show %s", expected)
                    .anyMatch(id -> id.equals(expected) || id.startsWith(expected + "/"));
        }
        assertThat(r.findings()).as("a corrupt ISIN checksum")
                .anyMatch(f -> f.ruleId().startsWith("ISIN/"));
        assertThat(r.findings()).as("a corrupt LEI checksum")
                .anyMatch(f -> f.ruleId().startsWith("LEI/"));
        assertThat(r.findings()).as("group id is mandatory in V8")
                .anyMatch(f -> f.ruleId().startsWith("PRESENCE/50/") && f.severity() == Severity.ERROR);

        // Only the one curated N/A leftover — anything else is V7 data leaking into the demo.
        assertThat(r.findings()).extracting(Finding::ruleId)
                .filteredOn(id -> id.startsWith("NOT_APPLICABLE/"))
                .containsOnly("NOT_APPLICABLE/54");
        assertThat(r.findings()).extracting(Finding::ruleId)
                .noneMatch(id -> id.startsWith("XF-15/") || id.startsWith("XF-09/"));
        // V8 makes 81/82/85 mandatory for every CIC 2 row; the generator fills them for the
        // corporate bonds, so they must not flood the demo with PRESENCE errors.
        assertThat(r.findings()).extracting(Finding::ruleId)
                .noneMatch(id -> id.matches("PRESENCE/(81|82|85)/.*"));

        assertThat(r.scores().get(ScoreCategory.OVERALL))
                .as("showcase overall score").isBetween(0.85, 0.999);
    }

    @Test
    void cleanV8FileHasNoDataErrorsAndNoV8SpecificFindings() throws Exception {
        QualityReport r = run("01_clean_v8.xlsx");
        assertThat(r.file().unmappedHeaders()).as("every header maps to a V8 field").isEmpty();
        List<Finding> errors = r.findings().stream()
                .filter(f -> f.severity() == Severity.ERROR)
                .filter(f -> f.ruleId().startsWith("FORMAT/")
                          || f.ruleId().startsWith("ISIN/")
                          || f.ruleId().startsWith("LEI/")
                          || f.ruleId().startsWith("XF-"))
                .toList();
        assertThat(errors).as("01_clean_v8 data errors").isEmpty();
        assertThat(r.findings()).extracting(Finding::ruleId)
                .noneMatch(id -> id.startsWith("NOT_APPLICABLE/"));
        // Issuer ids are mandatory for every CIC in V8 — the clean file fills them, so no
        // Solvency II presence error on 47/48/50/51 may remain.
        assertThat(r.findings()).extracting(Finding::ruleId)
                .noneMatch(id -> id.matches("PRESENCE/(47|48|50|51|115|119)/SOLVENCY_II"));
    }

    @Test
    void valuesInNotApplicableFieldsAreWarned() throws Exception {
        QualityReport r = run("02_na_fields_filled.xlsx");
        assertThat(r.findings()).extracting(Finding::ruleId)
                .contains("NOT_APPLICABLE/35", "NOT_APPLICABLE/36", "NOT_APPLICABLE/54",
                          "NOT_APPLICABLE/116", "NOT_APPLICABLE/120", "NOT_APPLICABLE/141");
        assertThat(r.findings().stream().filter(f -> f.ruleId().startsWith("NOT_APPLICABLE/")))
                .allSatisfy(f -> assertThat(f.severity()).isEqualTo(Severity.WARNING));
        // No V7-style pair/conditional rules may fire on the N/A columns.
        assertThat(r.findings()).extracting(Finding::ruleId)
                .noneMatch(id -> id.startsWith("XF-09/") || id.startsWith("XF-17/INDEX_TYPE")
                        || id.startsWith("XF-17/INDEX_NAME") || id.startsWith("XF-23/")
                        || id.startsWith("XF-24/"));
    }

    @Test
    void issuerIdentifierTypeCodesDriveTheLeiCheck() throws Exception {
        QualityReport r = run("03_issuer_identifier_types.xlsx");
        List<Finding> lei = r.findings().stream().filter(f -> f.ruleId().startsWith("LEI/")).toList();
        // Row 1: type 2 (VAT) → no LEI check on 47; but 115 is single-purpose → LEI/115.
        // Row 2: type 9 (internal) → no LEI check on 47; 140 single-purpose → LEI/140.
        // Row 3: type 1 with corrupt checksum → LEI/47/48.
        assertThat(lei).extracting(Finding::ruleId)
                .containsExactlyInAnyOrder("LEI/115", "LEI/140", "LEI/47/48");
        assertThat(lei).filteredOn(f -> f.ruleId().equals("LEI/47/48"))
                .extracting(Finding::rowIndex).containsExactly(3);
    }

    @Test
    void v8ClosedListsAreEnforced() throws Exception {
        QualityReport r = run("04_closed_lists_v8.xlsx");
        List<Finding> fmt = r.findings().stream()
                .filter(f -> f.ruleId().equals("FORMAT/56") || f.ruleId().equals("FORMAT/150")
                        || f.ruleId().equals("FORMAT/151")).toList();
        assertThat(fmt).extracting(Finding::ruleId)
                .containsExactlyInAnyOrder("FORMAT/56", "FORMAT/150", "FORMAT/151");
        assertThat(fmt).filteredOn(f -> f.ruleId().equals("FORMAT/56"))
                .extracting(Finding::rowIndex).as("'e2' on row 3 is valid, only 'e' on row 1 fails")
                .containsExactly(1);
    }

    @Test
    void v7VersionStringIsRejected() throws Exception {
        QualityReport r = run("05_wrong_version.xlsx");
        assertThat(r.findings()).anySatisfy(f -> {
            assertThat(f.ruleId()).isEqualTo("XF-15/TPT_VERSION");
            assertThat(f.severity()).isEqualTo(Severity.ERROR);
            assertThat(f.message()).contains("V8.0");
        });
    }

    @Test
    void floatingRateNoLongerNeedsIndexTypeAndName() throws Exception {
        QualityReport r = run("06_floating_rate_v8.xlsx");
        List<Finding> xf10 = r.findings().stream()
                .filter(f -> f.ruleId().equals("XF-10/INTEREST_RATE_TYPE")).toList();
        assertThat(xf10).hasSize(1);
        assertThat(xf10.get(0).fieldNum()).isEqualTo("34");
        assertThat(xf10.get(0).rowIndex()).isEqualTo(3);
    }

    private QualityReport run(String filename) throws Exception {
        Path p = samplesDir().resolve(filename);
        assertThat(Files.exists(p)).as("missing sample %s", p).isTrue();
        TptFile file = new TptFileLoader(CATALOG).load(p);
        List<Finding> findings = new ValidationEngine(CATALOG, new TptRuleSet(TptTemplate.V8_0))
                .validate(file, ALL);
        return new QualityScorer(CATALOG).score(file, ALL, findings);
    }
}
